/**
 * Bulk load-test data (SYS-1 bulk, Person 4): 10,000 subscriptions and 30,000 invoices
 * for the "every page under 2 s" check. LOCAL ONLY — remote D1 on the free plan allows
 * 100,000 row writes per day. Run after the base seed:
 *
 *   npm run db:seed:bulk
 *
 * Rows use the base seed's plans/products and simple plan-fee invoices so totals are
 * internally consistent (subtotal = total, no tax or discount).
 */
import { mkdirSync, writeFileSync } from "node:fs";

const SUBSCRIPTIONS = 10_000;
const INVOICES_PER_SUB = 3;
const CUSTOMERS = 2_000;
const today = new Date();
const iso = (d: Date) => d.toISOString().slice(0, 10);
const addMonths = (d: Date, m: number) => new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth() + m, Math.min(d.getUTCDate(), 28)));
const addDays = (d: Date, n: number) => new Date(d.getTime() + n * 86_400_000);
const plans = [
  { id: "seed-plan-monthly", price: 99900 },
  { id: "seed-plan-yearly", price: 999900 },
];

let seed = 7;
const rand = () => ((seed = (seed * 1664525 + 1013904223) % 2 ** 32) / 2 ** 32);

const out: string[] = ["-- Generated by scripts/seed-bulk.ts (load-test data, local only).", "PRAGMA foreign_keys = OFF;"];
const chunk = (table: string, cols: string[], rows: (string | number | null)[][]) => {
  for (let i = 0; i < rows.length; i += 500) {
    const values = rows
      .slice(i, i + 500)
      .map((r) => `(${r.map((v) => (v === null ? "NULL" : typeof v === "number" ? v : `'${String(v).replace(/'/g, "''")}'`)).join(",")})`)
      .join(",\n");
    out.push(`INSERT OR IGNORE INTO ${table} (${cols.join(",")}) VALUES\n${values};`);
  }
};

chunk(
  "customers",
  ["id", "email", "contact_name", "company_name"],
  Array.from({ length: CUSTOMERS }, (_, i) => [`bulk-cust-${i}`, `bulk${i}@loadtest.test`, `Load Test ${i}`, `Bulk Co ${i} (load test)`]),
);

const subs: (string | number | null)[][] = [];
const invoices: (string | number | null)[][] = [];
const payments: (string | number | null)[][] = [];
for (let i = 0; i < SUBSCRIPTIONS; i++) {
  const plan = i % 10 === 0 ? plans[1]! : plans[0]!;
  const start = addMonths(today, -(INVOICES_PER_SUB + Math.floor(rand() * 3)));
  const status = rand() < 0.85 ? "active" : "closed";
  const subId = `bulk-sub-${i}`;
  const customer = `bulk-cust-${i % CUSTOMERS}`;
  const billed = plan.id === "seed-plan-yearly" ? 1 : INVOICES_PER_SUB;
  const next = plan.id === "seed-plan-yearly" ? addMonths(start, 12) : addMonths(start, INVOICES_PER_SUB);
  subs.push([subId, `SUB-B${String(i).padStart(6, "0")}`, customer, plan.id, status, iso(start), billed, status === "active" ? iso(next) : null, 15]);
  for (let n = 0; n < INVOICES_PER_SUB; n++) {
    const periodStart = plan.id === "seed-plan-yearly" ? addMonths(start, 12 * n) : addMonths(start, n);
    if (periodStart > today) break;
    const issue = periodStart;
    const due = addDays(issue, 15);
    const paidRoll = rand();
    const invStatus = paidRoll < 0.75 ? "paid" : "confirmed";
    const invId = `bulk-inv-${i}-${n}`;
    invoices.push([
      invId, `INV-B${String(i * INVOICES_PER_SUB + n).padStart(7, "0")}`, subId, customer, iso(periodStart), iso(addDays(plan.id === "seed-plan-yearly" ? addMonths(periodStart, 12) : addMonths(periodStart, 1), -1)),
      invStatus, iso(issue), iso(due), plan.price, 0, 0, plan.price, invStatus === "paid" ? plan.price : 0,
    ]);
    if (invStatus === "paid") payments.push([`bulk-pay-${i}-${n}`, invId, customer, "upi", plan.price, iso(addDays(issue, Math.floor(rand() * 20)))]);
  }
}
chunk("subscriptions", ["id", "number", "customer_id", "plan_id", "status", "start_date", "billed_periods", "next_invoice_date", "payment_term_days"], subs);
chunk(
  "invoices",
  ["id", "number", "subscription_id", "customer_id", "period_start", "period_end", "status", "issue_date", "due_date", "subtotal", "discount_total", "tax_total", "total", "amount_paid"],
  invoices,
);
chunk("invoice_lines", ["id", "invoice_id", "description", "quantity", "unit_price", "amount"], invoices.map((r) => [`${r[0]}-l`, r[0] ?? null, "Plan fee (load test)", 1, r[9] ?? 0, r[9] ?? 0]));
chunk("payments", ["id", "invoice_id", "customer_id", "method", "amount", "paid_on"], payments);
out.push("PRAGMA foreign_keys = ON;");

mkdirSync(".seed", { recursive: true });
writeFileSync(".seed/bulk.sql", out.join("\n"));
console.log(`Wrote .seed/bulk.sql: ${subs.length} subscriptions, ${invoices.length} invoices, ${payments.length} payments.`);
